// Builds api/_lib/data/zipDistricts.js: every congressional district each ZIP
// code touches, from the Census Bureau's 119th Congressional District to 2020
// ZCTA relationship file. find_representatives (api/_lib/mcpTools.js) reads it
// so a ZIP that spans districts returns all of them instead of a centroid guess.
//
//   node scripts/build-zip-districts.mjs            download and write
//   node scripts/build-zip-districts.mjs <file>     build from a local copy
//
// Source: https://www2.census.gov/geo/docs/maps-data/data/rel2020/cd-sld/
// (public domain). Re-run when a new Congress's districts are published and
// update SOURCE_URL and CONGRESS together.
//
// A ZCTA (ZIP Code Tabulation Area) is the Census Bureau's area for a ZIP
// code. PO-box-only ZIP codes have no ZCTA; the tool falls back to the ZIP
// centroid for those. Shares are of the ZCTA's land area, not of its
// residents: the file carries no population. Parts under MIN_SHARE_PCT of the
// ZCTA are dropped as boundary slivers.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { FIPS_TO_STATE } from '../api/_lib/geocode.js'
import { normalizeCensusDistrict } from '../shared/atLargeStates.js'

export const CONGRESS = 119
export const SOURCE_URL = 'https://www2.census.gov/geo/docs/maps-data/data/rel2020/cd-sld/tab20_cd11920_zcta520_natl.txt'
export const MIN_SHARE_PCT = 1
const OUT = fileURLToPath(new URL('../api/_lib/data/zipDistricts.js', import.meta.url))

// Rows of the relationship file -> { "10001": "NY12", "42223": "KY1:68,TN7:32" }.
// One part is written bare; several carry each part's share of the ZCTA's land
// area in whole percent, largest first.
export function buildZipDistricts(text) {
  const lines = text.replace(/^﻿/, '').split(/\r?\n/).filter(Boolean)
  const head = lines[0].split('|')
  const col = (name) => {
    const i = head.indexOf(name)
    if (i === -1) throw new Error(`column ${name} missing from the relationship file`)
    return i
  }
  const CD = col(`GEOID_CD${CONGRESS}_20`)
  const ZCTA = col('GEOID_ZCTA5_20')
  const LAND = col('AREALAND_PART')
  const WATER = col('AREAWATER_PART')

  const parts = new Map()
  for (const line of lines.slice(1)) {
    const f = line.split('|')
    const zip = f[ZCTA]
    if (!/^\d{5}$/.test(zip || '')) continue
    const geoid = f[CD] || ''
    const state = FIPS_TO_STATE[geoid.slice(0, 2)]
    // "ZZ" marks water with no district.
    const district = normalizeCensusDistrict(geoid.slice(2))
    if (!state || district == null) continue
    const key = `${state}${district}`
    const list = parts.get(zip) || new Map()
    const prev = list.get(key) || { land: 0, water: 0 }
    list.set(key, { land: prev.land + (Number(f[LAND]) || 0), water: prev.water + (Number(f[WATER]) || 0) })
    parts.set(zip, list)
  }

  const out = {}
  for (const zip of [...parts.keys()].sort()) {
    const list = [...parts.get(zip)]
    const totalLand = list.reduce((n, [, a]) => n + a.land, 0)
    // A ZCTA that is all water has no land to share out; use total area.
    const size = (a) => (totalLand > 0 ? a.land : a.land + a.water)
    const total = list.reduce((n, [, a]) => n + size(a), 0)
    const shares = list
      .map(([key, a]) => ({ key, pct: total > 0 ? (size(a) / total) * 100 : 100 / list.length }))
      .sort((a, b) => b.pct - a.pct || a.key.localeCompare(b.key))
    const kept = shares.filter((s) => s.pct >= MIN_SHARE_PCT)
    const use = kept.length ? kept : shares.slice(0, 1)
    out[zip] = use.length === 1 ? use[0].key : use.map((s) => `${s.key}:${Math.max(1, Math.round(s.pct))}`).join(',')
  }
  return out
}

export function renderModule(map) {
  const zips = Object.keys(map)
  const body = zips.map((z) => `${z}=${map[z]}`).join(';')
  return [
    '// GENERATED by scripts/build-zip-districts.mjs; do not edit by hand.',
    `// ${zips.length} ZIP Code Tabulation Areas and the ${CONGRESS}th Congress districts each one touches.`,
    `// Source: ${SOURCE_URL}`,
    `export const ZIP_DISTRICTS_CONGRESS = ${CONGRESS}`,
    `export const ZIP_DISTRICTS_SOURCE = ${JSON.stringify(SOURCE_URL)}`,
    '// "zip=STATEdistrict" or "zip=STATEdistrict:pct,STATEdistrict:pct", joined by ";".',
    `export const ZIP_DISTRICTS = ${JSON.stringify(body)}`,
    '',
  ].join('\n')
}

async function main() {
  const local = process.argv[2]
  let text
  if (local) {
    text = readFileSync(local, 'utf8')
  } else {
    const res = await fetch(SOURCE_URL)
    if (!res.ok) throw new Error(`${res.status} from www2.census.gov`)
    text = await res.text()
  }
  const map = buildZipDistricts(text)
  mkdirSync(dirname(OUT), { recursive: true })
  writeFileSync(OUT, renderModule(map))
  const multi = Object.values(map).filter((v) => v.includes(',')).length
  console.log(`wrote ${OUT}: ${Object.keys(map).length} ZIP areas, ${multi} spanning more than one district`)
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().then(() => process.exit(0)).catch((err) => { console.error(err); process.exit(1) })
}
