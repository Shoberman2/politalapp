import { describe, expect, it, vi } from 'vitest'
import { getDeskDataForCongress } from '../../etl/historical/desks/index.js'
import { ingestSenateHistoricalOfficeDesks, validateDeskData } from '../../etl/sources/senateHistoricalOfficeDesks.js'

// The 119th Congress desk file is generated from the Senate's floor plans.
// These checks keep a hand edit or a bad regeneration from reaching the loader.

describe('119th Congress Senate desks', () => {
  const data = getDeskDataForCongress(119)!

  it('passes the loader validation', () => {
    expect(validateDeskData(data)).toEqual([])
  })

  it('places all 100 desks, 47 left of the aisle and 53 right, in four rows', () => {
    expect(data.desks).toHaveLength(100)
    expect(data.desks!.filter((d) => d.side === 'D')).toHaveLength(47)
    expect(data.desks!.filter((d) => d.side === 'R')).toHaveLength(53)
    expect([1, 2, 3, 4].map((arc) => data.desks!.filter((d) => d.arc === arc).length)).toEqual([16, 23, 28, 33])
  })

  it('has exactly one current senator at every desk, each at one desk', () => {
    const current = data.assignments.filter((a) => !a.vacatedAt)
    expect(current).toHaveLength(100)
    expect(current.every((a) => a.bioguideId)).toBe(true)
    expect(new Set(current.map((a) => a.deskId)).size).toBe(100)
    expect(new Set(current.map((a) => a.bioguideId)).size).toBe(100)
  })

  it('carries the corrected ids for the two links the Senate file gets wrong', () => {
    const at = (deskId: number) => data.assignments.find((a) => a.deskId === deskId && !a.vacatedAt)!.bioguideId
    expect(at(32)).toBe('O000174') // Jon Ossoff, not P000612 (David Perdue)
    expect(at(75)).toBe('H000273') // John Hickenlooper, not O000174
    expect(data.assignments.some((a) => a.bioguideId === 'P000612')).toBe(false)
  })

  it('names the three desks by their real numbers and retires the stub ones', () => {
    const named = Object.fromEntries(data.desks!.filter((d) => d.famousName).map((d) => [d.deskId, d.famousName]))
    expect(named).toEqual({ 29: 'Daniel Webster Desk', 49: 'Candy Desk', 60: 'Jefferson Davis Desk' })
    expect(data.retiredFamousDeskIds).toEqual([64, 80, 91])
    expect(data.lineageRows!.every((l) => [29, 49, 60].includes(l.deskId))).toBe(true)
  })

  it('rejects a file with a duplicated desk or a senator at two desks', () => {
    const twoDesks = { ...data, assignments: [...data.assignments, { deskId: 1, bioguideId: 'S001181', assignedAt: '2026-08-01' }] }
    expect(validateDeskData(twoDesks).join(' ')).toMatch(/current occupants|holds 2 desks/)
    const dupDesk = { ...data, desks: [...data.desks!.slice(1), data.desks![1]] }
    expect(validateDeskData(dupDesk).join(' ')).toMatch(/100 distinct desks/)
  })
})

// Records every Supabase call the loader makes and answers from `answers`.
function fakeSupabase(answers: { existing?: Array<{ desk_id: number; assigned_at: string }>; failUpsertOn?: string } = {}) {
  const calls: Array<{ table: string; op: string; filters: Array<[string, unknown]>; rows?: unknown[] }> = []
  const client = {
    from(table: string) {
      const call = { table, op: '', filters: [] as Array<[string, unknown]>, rows: undefined as unknown[] | undefined }
      const builder: any = {
        select() { call.op = 'select'; calls.push(call); return builder },
        delete() { call.op = 'delete'; calls.push(call); return builder },
        upsert(rows: unknown[]) {
          call.op = 'upsert'; call.rows = rows; calls.push(call)
          return Promise.resolve({ error: answers.failUpsertOn === table ? { message: `${table} is read-only` } : null })
        },
        eq(col: string, value: unknown) { call.filters.push([col, value]); return builder },
        in(col: string, value: unknown) { call.filters.push([col, value]); return builder },
        then(resolve: (v: unknown) => unknown) {
          if (call.op === 'select') return resolve({ data: answers.existing ?? [], error: null })
          return resolve({ error: null, count: 0 })
        },
      }
      return builder
    },
  }
  return { client: client as any, calls }
}

// Generated by /ship test coverage audit (2026-11-15).
// Value: protects=validateDeskData names each kind of bad row, and the loader
//   writes nothing to Supabase when the desk file fails it;
//   fails_when=a check (id range, bioguide shape, row, shared slot, repeated
//   start date) is dropped, or the loader writes before or despite validating;
//   why_new=the existing rejection case covers only a duplicated desk and a
//   senator at two desks, and no test calls ingestSenateHistoricalOfficeDesks;
//   seam=none;
//   no_claim=the live tables' constraints (Supabase client is a recording fake)
describe('desk file validation', () => {
  const data = getDeskDataForCongress(119)!
  const first = data.assignments[0]
  const withAssignment = (patch: object) => ({ ...data, assignments: [{ ...first, ...patch }, ...data.assignments.slice(1)] })
  const withDesk = (patch: object) => ({ ...data, desks: [{ ...data.desks![0], ...patch }, ...data.desks!.slice(1)] })

  it.each([
    ['a desk number past 100', withAssignment({ deskId: 101 }), /assignments: desk id 101 is outside 1-100/],
    ['a malformed bioguide id', withAssignment({ bioguideId: 'ossoff' }), /has bioguide id "ossoff"/],
    ['two rows for one desk starting the same day', { ...data, assignments: [...data.assignments, { ...first }] }, /has two rows starting/],
    ['a fifth row of desks', withDesk({ arc: 5 }), /has arc 5/],
    ['two desks in one spot', withDesk({ arc: data.desks![1].arc, position: data.desks![1].position }), /two desks share row/],
  ])('reports %s', (_label, bad, problem) => {
    expect(validateDeskData(bad as typeof data).join('\n')).toMatch(problem)
  })

  it('accepts a desk that is empty for now (no senator on record)', () => {
    expect(validateDeskData(withAssignment({ bioguideId: null }))).toEqual([])
  })

  it('writes nothing when the file fails validation', async () => {
    vi.spyOn(console, 'error').mockImplementation(() => {})
    vi.spyOn(console, 'log').mockImplementation(() => {})
    const { client, calls } = fakeSupabase()
    // The loader reads the 119th file itself, so spoil the real row for the
    // length of this test and put it back afterwards.
    const original = first.bioguideId
    first.bioguideId = 'ossoff'
    try {
      const result = await ingestSenateHistoricalOfficeDesks(client, 119, '2025-01-03')
      expect(result.status).toBe('failed')
      expect(result.records_loaded).toBe(0)
      expect(result.errors.join(' ')).toMatch(/bioguide id "ossoff"/)
      expect(calls).toEqual([])
    } finally {
      first.bioguideId = original
      vi.restoreAllMocks()
    }
  })
})

// Generated by /ship test coverage audit (2026-11-15).
// Value: protects=a desk load treats the file as the whole Congress: it writes
//   all 100 desks, removes assignment rows the file no longer has, clears the
//   retired "famous" desks' lineage, and reports a write error as failed;
//   fails_when=superseded assignment rows are left behind or a kept row is
//   deleted, the retired ids are not cleared, or a Supabase error is reported
//   as success;
//   why_new=no test calls ingestSenateHistoricalOfficeDesks at all;
//   seam=none;
//   no_claim=real upsert conflict handling or row counts in Postgres (recording fake)
describe('desk load', () => {
  const data = getDeskDataForCongress(119)!
  const quiet = () => {
    vi.spyOn(console, 'error').mockImplementation(() => {})
    vi.spyOn(console, 'log').mockImplementation(() => {})
  }

  it('writes the whole file and removes only the rows it has superseded', async () => {
    quiet()
    const kept = { desk_id: data.assignments[0].deskId, assigned_at: data.assignments[0].assignedAt ?? '2025-01-03' }
    const stale = { desk_id: 64, assigned_at: '2024-01-01' }
    const { client, calls } = fakeSupabase({ existing: [kept, stale] })

    const result = await ingestSenateHistoricalOfficeDesks(client, 119, '2025-01-03')
    vi.restoreAllMocks()

    expect(result.status).toBe('success')
    expect(result.errors).toEqual([])
    expect(result.records_loaded).toBe(100 + data.assignments.length + data.lineageRows!.length)

    const upserts = Object.fromEntries(calls.filter((c) => c.op === 'upsert').map((c) => [c.table, c.rows!]))
    expect(upserts.senate_desks).toHaveLength(100)
    expect(upserts.senate_desk_assignments).toHaveLength(data.assignments.length)
    expect((upserts.senate_desk_assignments as any[]).every((r) => r.congress === 119 && r.assigned_at && r.source === data.source)).toBe(true)
    expect(upserts.senate_desk_lineage).toHaveLength(data.lineageRows!.length)

    const deletes = calls.filter((c) => c.op === 'delete')
    expect(deletes.filter((c) => c.table === 'senate_desk_lineage').map((c) => c.filters)).toEqual([[['desk_id', [64, 80, 91]], ['source', 'senate_historical_office']]])
    expect(deletes.filter((c) => c.table === 'senate_desk_assignments').map((c) => c.filters)).toEqual([
      [['congress', 119], ['desk_id', 64], ['assigned_at', '2024-01-01']],
    ])
  })

  it('reports a failed write as failed, not as a load', async () => {
    quiet()
    const { client } = fakeSupabase({ failUpsertOn: 'senate_desk_assignments' })
    const result = await ingestSenateHistoricalOfficeDesks(client, 119, '2025-01-03')
    vi.restoreAllMocks()
    expect(result.status).toBe('failed')
    expect(result.records_loaded).toBe(0)
    expect(result.errors).toEqual(['senate_desk_assignments is read-only'])
  })
})
