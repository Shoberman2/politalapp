#!/usr/bin/env bash
#
# Xcode Cloud post-clone hook.
# https://developer.apple.com/documentation/xcode/writing-custom-build-scripts
#
# Xcode Cloud runs this after it clones the repo and before it looks up
# ios/BallotWatch.xcodeproj. That project is generated from ios/project.yml and
# is gitignored. ios/BallotWatch/Secrets.plist is also gitignored and is
# written here from workflow environment variables.
#
# Required environment variables, same names as ios/scripts/make-secrets.sh
# and the repo-root .env.example:
#   VITE_SUPABASE_URL
#   VITE_SUPABASE_ANON_KEY
#
# Aliases, also documented in .env.example and ios/BallotWatch/Secrets.example.plist:
#   SUPABASE_URL
#   SUPABASE_ANON_KEY
#
# Set these in the Xcode Cloud workflow Environment section. Do not commit
# values. This script does not read .env or any other secret file, and it
# does not use a service-role key.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
IOS_DIR="$REPO_ROOT/ios"
SECRETS_PLIST="$IOS_DIR/BallotWatch/Secrets.plist"

log() { printf '%s\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }

# First non-empty documented variable. Never print the value.
env_first() {
  local name
  for name in "$@"; do
    if [ -n "${!name+x}" ] && [ -n "${!name}" ]; then
      printf '%s' "${!name}"
      return 0
    fi
  done
  return 1
}

require_documented() {
  local label="$1"
  shift
  local value=""
  if ! value="$(env_first "$@")"; then
    die "missing ${label}. Set one of these environment variables in the Xcode Cloud workflow (Environment): $*"
  fi
  printf '%s' "$value"
}

xml_escape() {
  # Bash 5.2 treats & in the replacement as the matched text, so a literal
  # ampersand in &amp; / &lt; must be written as \&.
  local s="$1"
  s=${s//&/\&amp;}
  s=${s//</\&lt;}
  s=${s//>/\&gt;}
  s=${s//\"/\&quot;}
  s=${s//\'/\&apos;}
  printf '%s' "$s"
}

# Resolve required env vars first so a misconfigured workflow fails before
# Homebrew work. Avoid `set -x` leaking values into Xcode Cloud logs.
{ set +x; } 2>/dev/null

supabase_url="$(require_documented "Supabase URL" VITE_SUPABASE_URL SUPABASE_URL)"
supabase_anon_key="$(require_documented "Supabase anon key" VITE_SUPABASE_ANON_KEY SUPABASE_ANON_KEY)"

case "$supabase_url" in
  YOUR_*) die "the Supabase URL environment variable still has a placeholder YOUR_ value. Set the real URL in the Xcode Cloud workflow." ;;
esac
case "$supabase_anon_key" in
  YOUR_*) die "the Supabase anon key environment variable still has a placeholder YOUR_ value. Set the real anon key in the Xcode Cloud workflow." ;;
esac

if ! command -v xcodegen >/dev/null 2>&1; then
  if ! command -v brew >/dev/null 2>&1; then
    die "XcodeGen is not installed, and Homebrew was not found. Install XcodeGen (brew install xcodegen) on this runner, or use an Xcode Cloud environment that includes Homebrew."
  fi
  log "XcodeGen not found; installing with Homebrew."
  HOMEBREW_NO_AUTO_UPDATE=1 brew install xcodegen
fi

command -v xcodegen >/dev/null 2>&1 || die "xcodegen is still missing after the Homebrew install."

log "Generating ios/BallotWatch.xcodeproj from ios/project.yml"
( cd "$IOS_DIR" && xcodegen generate )

if [ ! -d "$IOS_DIR/BallotWatch.xcodeproj" ]; then
  die "xcodegen finished but ios/BallotWatch.xcodeproj was not created."
fi

url_xml="$(xml_escape "$supabase_url")"
key_xml="$(xml_escape "$supabase_anon_key")"
unset supabase_url supabase_anon_key

cat > "$SECRETS_PLIST" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by ci_scripts/ci_post_clone.sh from Xcode Cloud environment variables. Gitignored: do not commit. -->
<plist version="1.0">
<dict>
	<key>SUPABASE_URL</key>
	<string>${url_xml}</string>
	<key>SUPABASE_ANON_KEY</key>
	<string>${key_xml}</string>
</dict>
</plist>
PLIST

unset url_xml key_xml

if [ ! -s "$SECRETS_PLIST" ]; then
  die "failed to write $SECRETS_PLIST"
fi

log "Wrote $SECRETS_PLIST from Xcode Cloud environment variables."
log "Xcode Cloud post-clone setup is complete."
